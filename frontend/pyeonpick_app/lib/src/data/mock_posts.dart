import '../models/post.dart';

PostDetails _details({
  required String step,
  String tip = '',
  String caution = '',
  List<String> situations = const <String>[],
}) {
  return PostDetails(
    eatingSteps: <String>[step],
    tips: tip.isEmpty ? const <String>[] : <String>[tip],
    cautions: caution.isEmpty ? const <String>[] : <String>[caution],
    situationTags: situations,
    reviewPoints: const <String>[],
    prepTimeTag: '',
  );
}

PostReview _review({
  required String id,
  required String nickname,
  required String text,
  required double rating,
  required List<String> tags,
  required int sweet,
  required int salty,
  required int spicy,
  required int sour,
  String caution = '',
}) {
  return PostReview(
    id: id,
    authorId: 'reviewer-$id',
    authorNickname: nickname,
    text: text,
    rating: rating,
    tags: tags,
    sweet: sweet,
    salty: salty,
    spicy: spicy,
    sour: sour,
    caution: caution,
    createdAt: DateTime(2026, 6, 20, 10, int.parse(id.substring(1))),
  );
}

Post _post({
  required String id,
  required String nickname,
  required String title,
  required String content,
  required int price,
  required List<String> categories,
  required int likes,
  required int dislikes,
  required DateTime createdAt,
  required String imageUrl,
  required PostDetails details,
  required int calories,
  required double rating,
  DateTime? topWorstEnteredAt,
  List<PostReview> reviews = const <PostReview>[],
}) {
  return Post(
    id: id,
    authorId: 'seed-author-$id',
    authorNickname: nickname,
    title: title,
    content: content,
    priceMin: price,
    priceMax: price,
    categories: categories,
    likes: likes,
    dislikes: dislikes,
    comments: const <PostComment>[],
    createdAt: createdAt,
    imageData: null,
    imageUrl: imageUrl,
    imageDatas: const <String>[],
    imageUrls: <String>[imageUrl],
    details: details,
    likedByMe: false,
    dislikedByMe: false,
    topFiveEnteredAt: null,
    topWorstEnteredAt: topWorstEnteredAt,
    calories: calories,
    rating: rating,
    reviews: reviews,
  );
}

